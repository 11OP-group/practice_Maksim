grade = int(input())

match grade:
    case 5:
        print("Результат: отлично. Это выдающиеся результаты.")
    case 4:
        print("Результат: хорошо. Это хороший результат.")
    case 3:
        print("Результат: удовлетворительно. Необходимо подучить материал.")
    case 2:
        print("Результат: неудовлетворительно. Требуется пересдача.")
    case _:
        print("Ошибка. Оценка должна быть от 2 до 5.")