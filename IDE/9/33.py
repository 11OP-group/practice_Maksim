# Запрашиваем у пользователя число n
n = int(input("Введите число n: "))

factorial = 1  # Переменная для хранения результата произведения

# Перебираем все числа от 1 до n включительно
for i in range(1, n + 1):
    factorial *= i  # Умножаем текущий результат на i (сокращенно от factorial = factorial * i)

print(f"Факториал числа {n} равен {factorial}")
