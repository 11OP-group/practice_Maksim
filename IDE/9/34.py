# Вводим два целых числа m и n
m = int(input("Введите число m: "))
n = int(input("Введите число n: "))

if m < n:
    # Если m меньше n, выводим по возрастанию
    # range(m, n + 1) идет от m до n включительно
    for i in range(m, n + 1):
        print(i)
else:
    # Иначе выводим по убыванию
    # range(m, n - 1, -1) идет от m вниз до n включительно с шагом -1
    for i in range(m, n - 1, -1):
        print(i)
