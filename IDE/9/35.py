# Вводим два натуральных числа m и n (m <= n)
m = int(input("Введите число m: "))
n = int(input("Введите число n: "))

# Перебираем числа от m до n включительно
for i in range(m, n + 1):
    # Условие 1: кратно 17 (остаток от деления на 17 равен 0)
    cond1 = (i % 17 == 0)

    # Условие 2: оканчивается на 9 (остаток от деления на 10 равен 9)
    cond2 = (i % 10 == 9)

    # Условие 3: кратно 3 и 5 одновременно
    cond3 = (i % 3 == 0 and i % 5 == 0)

    # Если выполняется хотя бы одно (or) из условий, выводим число
    if cond1 or cond2 or cond3:
        print(i)
